export default function AIAgentOverview({
  tabRef,
  activeTab,
  setActiveTab,
  riskHostCount,
  bashAlarmsCount,
  maliciousAlarmsCount,
  aiAgentHostList,
  hasFilterAlarm,
  setHasFilterAlarm,
}: any) {
  const scrollToTab = () => {
    window.setTimeout(() => {
      tabRef?.current?.scrollIntoView?.({ behavior: "smooth" });
    }, 10);
  };

  const stats = [
    {
      key: "assets",
      label: "AI Agent资产",
      value: aiAgentHostList?.length || 0,
      icon: <IconAssets />,
      selected: activeTab === ASSETS && !hasFilterAlarm,
      onClick: () => {
        setActiveTab?.(ASSETS);
        setHasFilterAlarm?.(false);
        scrollToTab();
      },
    },
    {
      key: "risk",
      label: "存在风险/告警资产",
      value: riskHostCount || 0,
      icon: <IconRisk />,
      tooltip: '存在"恶意Skills"或存在"威胁告警"的AI Agent资产。',
      selected: activeTab === ASSETS && hasFilterAlarm,
      onClick: () => {
        setActiveTab?.(ASSETS);
        setHasFilterAlarm?.(true);
        scrollToTab();
      },
    },
    {
      key: "alarm",
      label: "威胁告警",
      value: (bashAlarmsCount || 0) + (maliciousAlarmsCount || 0),
      icon: <IconAlarm />,
      selected: activeTab === ALARMS,
      onClick: () => {
        setActiveTab?.(ALARMS);
        setHasFilterAlarm?.(false);
        scrollToTab();
      },
    },
  ];

  return (
    <div className="grid grid-cols-3 gap-5">
      {stats.map((stat) => (
        <SurfaceCard
          key={stat.key}
          hover
          role="button"
          tabIndex={0}
          onClick={stat.onClick}
          data-state={stat.selected ? "selected" : undefined}
          className="px-6 py-5 flex flex-col gap-4 text-left cursor-pointer border-[#E5E5E5]"
        >
          <div className="flex items-center gap-1">
            {stat.icon}
            <CardTitle>{stat.label}</CardTitle>
            {stat.tooltip ? (
              <TooltipProvider>
                <Tooltip>
                  <TooltipTrigger asChild>
                    <Info
                      className="w-3.5 h-3.5 text-[#A3A3A3] cursor-help shrink-0 ml-0.5"
                      onClick={(e) => e.stopPropagation()}
                    />
                  </TooltipTrigger>
                  <TooltipContent>{stat.tooltip}</TooltipContent>
                </Tooltip>
              </TooltipProvider>
            ) : null}
          </div>
          <StatNumber>{stat.value}</StatNumber>
        </SurfaceCard>
      ))}
    </div>
  );
}
