#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');

// 读取 MANIFEST.json
const manifestPath = path.resolve(packageRoot, 'MANIFEST.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

// 组件信息映射
const componentInfo = new Map();

// 第一步：从 componentSpecs 列表中收集
const componentSpecsDir = path.resolve(packageRoot, 'component-specs');
for (const specFile of manifest.componentSpecs || []) {
  const specPath = path.resolve(packageRoot, specFile);
  if (fs.existsSync(specPath)) {
    const baseName = path.basename(specFile, '.md');
    
    // 查找对应的 React 和 CSS 文件
    const possibleReactFiles = [
      `${baseName}.tsx`,
      `${baseName}/index.tsx`,
      `${baseName}/${baseName}.tsx`,
    ];
    
    const possibleCssFiles = [
      `${baseName}.css`,
      `${baseName}/index.css`,
      `${baseName}/${baseName}.css`,
    ];

    let reactImpl = null;
    let cssImpl = null;

    // 查找 React 实现
    for (const file of possibleReactFiles) {
      const fullPath = path.resolve(packageRoot, 'portable/react', file);
      if (fs.existsSync(fullPath)) {
        reactImpl = file;
        break;
      }
    }

    // 查找 CSS 实现
    for (const file of possibleCssFiles) {
      const fullPath = path.resolve(packageRoot, 'portable/css', file);
      if (fs.existsSync(fullPath)) {
        cssImpl = file;
        break;
      }
    }

    componentInfo.set(baseName, {
      spec: specFile,
      react: reactImpl,
      css: cssImpl,
      isFramework: false,
    });
  }
}

// 第二步：扫描 portable/react 中的实现
const reactDir = path.resolve(packageRoot, 'portable/react');
if (fs.existsSync(reactDir)) {
  for (const file of fs.readdirSync(reactDir)) {
    if (file.endsWith('.tsx')) {
      const baseName = file.replace('.tsx', '');
      if (!componentInfo.has(baseName)) {
        componentInfo.set(baseName, {
          spec: null,
          react: file,
          css: null,
          isFramework: true,
        });
      }
    }
  }
}

// 第三步：生成映射表 Markdown
const components = Array.from(componentInfo.entries())
  .sort((a, b) => a[0].localeCompare(b[0]));

const now = new Date().toISOString().split('T')[0];

const markdown = `# Component Reference Mapping

ClawPro Portable Design Skill 的组件三层映射表。

**最后更新**: ${now}  
**总组件数**: ${components.length}

---

## Quick Reference Table

| 组件 | Spec 文件 | React 实现 | CSS 文件 | 类型 |
|------|----------|----------|---------|------|
${components.map(([name, info]) => {
  const specLink = info.spec ? `[\`${path.basename(info.spec)}\`](../component-specs/${path.basename(info.spec)})` : '-';
  const reactLink = info.react ? `[\`${info.react}\`](../portable/react/${info.react})` : '-';
  const cssLink = info.css ? `[\`${info.css}\`](../portable/css/${info.css})` : '-';
  const type = info.isFramework ? '🔧 Framework' : '📦 UI';
  return `| ${name} | ${specLink} | ${reactLink} | ${cssLink} | ${type} |`;
}).join('\n')}

---

## Lookup Index

### By Component Name

${components.map(([name, info]) => {
  const status = (info.spec && info.react && info.css) ? '✓ Complete' : '⚠ Partial';
  return `- **${name}** (${status})
  - Spec: ${info.spec ? '✓' : '✗'}
  - React: ${info.react ? '✓' : '✗'}
  - CSS: ${info.css ? '✓' : '✗'}`;
}).join('\n')}

---

## By Implementation Type

### UI Components (with Specs)
${components
  .filter(([, info]) => !info.isFramework && info.spec)
  .map(([name]) => `- ${name}`)
  .join('\n')}

### Framework Components (without Specs)
${components
  .filter(([, info]) => info.isFramework)
  .map(([name]) => `- ${name}`)
  .join('\n')}

---

## Coverage Analysis

### Complete Implementations (3/3 layers)
${components
  .filter(([, info]) => info.spec && info.react && info.css)
  .map(([name]) => `- ${name}`)
  .join('\n')}

### Partial Implementations
${components
  .filter(([, info]) => {
    const count = [info.spec, info.react, info.css].filter(Boolean).length;
    return count > 0 && count < 3;
  })
  .map(([name, info]) => `- ${name} (${[info.spec ? 'spec' : null, info.react ? 'react' : null, info.css ? 'css' : null].filter(Boolean).join(', ')})`)
  .join('\n')}

---

## MANIFEST Validation

Run \`npm run verify-manifest\` to validate this mapping against actual files.

**Last validated**: ${now}

---

**Generated by**: \`scripts/generate-component-mapping.mjs\`  
**Auto-update**: Yes (regenerate from actual files)
`;

// 写入文件
const outputPath = path.resolve(packageRoot, 'references/component-mapping.md');
fs.writeFileSync(outputPath, markdown);

console.log(`Generated component-mapping.md with ${components.length} components`);
console.log(`Output: ${outputPath}`);

process.exit(0);
