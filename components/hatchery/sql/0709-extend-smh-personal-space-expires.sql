-- 批量延长 smh_personal_spaces 个人空间的过期时间。
-- 背景：将所有过期时间早于（或等于）目标时间点的个人空间统一延长到 2026-08-15 23:59:59，
--   用于一次性调整存量个人空间的到期时间。
-- 说明：
--   1. 仅更新 expires_at <= '2026-08-15 23:59:59' 的记录，即到期时间在目标时间点之前（含相等）的记录。
--   2. expires_at 为 NULL（永久 / 未设置过期时间）的记录不受影响，NULL 不满足 <= 比较条件；
--      业务上创建个人空间时一定会写入 expires_at，正常不存在 NULL 记录。
UPDATE `smh_personal_spaces`
SET `expires_at` = '2026-08-15 23:59:59'
WHERE `expires_at` <= '2026-08-15 23:59:59';
