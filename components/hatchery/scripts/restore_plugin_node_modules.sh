#!/bin/bash
set -euo pipefail

# ========== 升级后修复 extensions 下各插件依赖与 openclaw 软链 ==========
# 背景：
#   backup_pre_reinstall.sh 打包时排除了 ~/.openclaw/extensions/*/node_modules，
#   restore_post_reinstall.sh 解压恢复后，这些插件目录会缺失依赖；同时 ESM 原生
#   import "openclaw/..." 需要在每个插件 node_modules 下存在到全局 openclaw 包的
#   软链。本脚本在 restore_post_reinstall.sh 完成后单独下发执行，专注做两件事：
#     1) 对每个含 package.json 但缺失 node_modules 的插件目录补装生产依赖；
#     2) 重建 plugin_dir/node_modules/openclaw -> 全局 openclaw 包 的软链。
#
# 调用方：controller/openclaw_upgrade.go 通过 TAT 以 runtimeUser 身份下发执行。
# 不进入 rootRequiredTATScripts 白名单：以普通用户执行，HOME / PNPM_HOME / npm
# 全局路径都指向运行用户目录，无需切换身份。

export PATH="$HOME/.npm-global/bin:$PATH"
export PNPM_HOME="${PNPM_HOME:-$HOME/.local/share/pnpm}"
export PATH="$PNPM_HOME:$HOME/.local/bin:$PATH"
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"

# ========== 日志系统初始化（与其他 scripts/*.sh 保持一致） ==========
# 所有 stdout/stderr 通过 tee 同时落到 ~/.openclaw/logs/restore_plugin_node_modules.log，
# 便于升级失败后到目标机器排障；调用方（TAT）仍能从 stdout 拿到原始输出。
LOG_DIR="${HOME}/.openclaw/logs"
if [ ! -d "$LOG_DIR" ]; then
    mkdir -p "$LOG_DIR" 2>/dev/null || true
fi
SCRIPT_NAME="restore_plugin_node_modules"
LOG_FILE="$LOG_DIR/${SCRIPT_NAME}.log"
# 若日志目录/文件不可写，则退回到不重定向，避免 exec 失败导致脚本整体崩溃
if { : >> "$LOG_FILE"; } 2>/dev/null; then
    exec > >(tee -a "$LOG_FILE") 2>&1
fi
echo ""
echo "========== 日志开始: $(date '+%Y-%m-%d %H:%M:%S') =========="

LOG_PREFIX="[restore-plugin-node-modules]"

EXT_DIR="${OPENCLAW_STATE_DIR:-$HOME/.openclaw}/extensions"

echo "${LOG_PREFIX} === 修复 OpenClaw 插件依赖与 openclaw 软链 ==="
echo "${LOG_PREFIX} extensions 目录: $EXT_DIR"
echo "${LOG_PREFIX} PNPM_HOME: $PNPM_HOME"

if [ ! -d "$EXT_DIR" ]; then
    echo "${LOG_PREFIX} extensions 目录不存在，无需修复"
    echo "========== 日志结束: $(date '+%Y-%m-%d %H:%M:%S') =========="
    exit 0
fi

# ========== 定位全局 openclaw 包目录（pnpm 全局安装路径） ==========
GLOBAL_OPENCLAW=""
if [ -d "$HOME/.local/share/pnpm/global" ]; then
    GLOBAL_OPENCLAW=$(find "$HOME/.local/share/pnpm/global" -maxdepth 6 -type d \
        -path "*/.pnpm/openclaw@*/node_modules/openclaw" 2>/dev/null | head -1)
fi

if [ -n "$GLOBAL_OPENCLAW" ] && [ -d "$GLOBAL_OPENCLAW" ]; then
    echo "${LOG_PREFIX} 全局 openclaw 包: $GLOBAL_OPENCLAW"
else
    echo "${LOG_PREFIX} Warning: global openclaw package not found（仅跳过软链步骤，依赖修复仍会执行）"
fi

# ========== 遍历各插件目录修复 ==========
fixed_count=0
skipped_count=0
failed_count=0

for plugin_dir in "$EXT_DIR"/*/; do
    [ -d "$plugin_dir" ] || continue
    plugin_dir="${plugin_dir%/}"
    id="$(basename "$plugin_dir")"

    # skillhub 由其官方安装脚本（restore_post_reinstall.sh 步骤 7）独立管理，跳过
    if [ "$id" = "skillhub" ]; then
        echo "${LOG_PREFIX} [$id] skillhub 由官方脚本管理，跳过"
        skipped_count=$((skipped_count + 1))
        continue
    fi

    # 仅处理含 package.json 的插件目录
    if [ ! -f "$plugin_dir/package.json" ]; then
        echo "${LOG_PREFIX} [$id] 无 package.json，跳过"
        skipped_count=$((skipped_count + 1))
        continue
    fi

    # 1) 判断是否需要补装依赖：node_modules 不存在或为空
    needs_install=0
    if [ ! -d "$plugin_dir/node_modules" ]; then
        needs_install=1
    elif ! find "$plugin_dir/node_modules" -mindepth 1 -maxdepth 1 -print -quit 2>/dev/null | grep -q .; then
        needs_install=1
    fi

    if [ "$needs_install" -eq 1 ]; then
        # 仅当 package.json 声明了 dependencies 才执行 install
        has_deps=0
        if command -v jq >/dev/null 2>&1; then
            if jq -e '(.dependencies // {}) | length > 0' "$plugin_dir/package.json" >/dev/null 2>&1; then
                has_deps=1
            fi
        else
            # 无 jq 时退化为 grep 粗判
            if grep -q '"dependencies"' "$plugin_dir/package.json" 2>/dev/null; then
                has_deps=1
            fi
        fi

        if [ "$has_deps" -eq 1 ]; then
            install_ok=0
            if command -v pnpm >/dev/null 2>&1; then
                echo "${LOG_PREFIX} [$id] 补装依赖：pnpm install --prod"
                if (cd "$plugin_dir" && timeout --kill-after=10 300 env CI=true pnpm install --prod); then
                    install_ok=1
                else
                    echo "${LOG_PREFIX} [$id] ⚠ pnpm install 失败，回退尝试 npm install"
                fi
            fi

            if [ "$install_ok" -eq 0 ] && command -v npm >/dev/null 2>&1; then
                echo "${LOG_PREFIX} [$id] 补装依赖：npm install --omit=dev"
                if (cd "$plugin_dir" && timeout --kill-after=10 300 env CI=true npm install --omit=dev --no-audit --no-fund); then
                    install_ok=1
                fi
            fi

            if [ "$install_ok" -eq 1 ]; then
                fixed_count=$((fixed_count + 1))
            else
                echo "${LOG_PREFIX} [$id] ✗ 依赖安装失败"
                failed_count=$((failed_count + 1))
            fi
        else
            echo "${LOG_PREFIX} [$id] package.json 无 dependencies，跳过依赖安装"
        fi
    fi

    # 2) 软链全局 openclaw 到插件 node_modules，避免 ESM 原生
    #    import "openclaw/..." 找不到包
    if [ -n "$GLOBAL_OPENCLAW" ] && [ -d "$GLOBAL_OPENCLAW" ]; then
        mkdir -p "$plugin_dir/node_modules"
        ln -sfn "$GLOBAL_OPENCLAW" "$plugin_dir/node_modules/openclaw"
        echo "${LOG_PREFIX} [$id] ✓ openclaw 软链 -> $GLOBAL_OPENCLAW"
    else
        echo "${LOG_PREFIX} [$id] ⚠ 无全局 openclaw 包，跳过软链"
    fi
done

echo ""
echo "${LOG_PREFIX} === 修复完成: 安装 ${fixed_count} 个，跳过 ${skipped_count} 个，失败 ${failed_count} 个 ==="
echo "========== 日志结束: $(date '+%Y-%m-%d %H:%M:%S') =========="
echo ""

# 失败不阻断升级主流程，统一返回 0；失败明细已通过 stderr/stdout 输出供排查
exit 0
